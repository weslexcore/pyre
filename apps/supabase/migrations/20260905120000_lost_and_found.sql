-- Private bucket for item photos. Its own bucket rather than sharing
-- incident-media: a signed-URL mistake in one tool should not reach the
-- other's media, and incident photos are far more sensitive. Same shape and
-- limits as the other two.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'lost-found-media',
  'lost-found-media',
  false,
  52428800,
  array[
    'image/jpeg', 'image/png', 'image/webp', 'image/heic', 'image/heif', 'image/gif',
    'video/mp4', 'video/quicktime', 'video/webm',
    'application/pdf'
  ]
)
on conflict (id) do nothing;

