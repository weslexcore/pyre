-- App access is service-role (bypasses RLS) and gated in-route by
-- requirePage/hasLostFoundManage; these policies are the forward-looking
-- convention the other admin tables follow. No delete policy on
-- lost_found_events: the audit trail is append-only.
create policy "admins can select lost found items"
  on public.lost_found_items for select
  using (public.is_admin());

create policy "admins can insert lost found items"
  on public.lost_found_items for insert
  with check (public.is_admin());

